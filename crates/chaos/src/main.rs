//! `hlchaos` CLI.

use chaos::runner::{self, RunConfig};
use chaos::schedule::{EpisodeKind, Scheduler, SchedulerConfig};
use chaos::{checker::SafetyChecker, parse_duration_ms};
use clap::{Parser, Subcommand};
use std::path::PathBuf;

#[derive(Parser)]
#[command(name = "hlchaos", about = "hlbft fault-injection harness (TEST_PLAN AC1)")]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

fn dur(s: &str) -> Result<u64, String> {
    parse_duration_ms(s)
}

#[derive(Clone, Debug)]
struct KindList(Vec<EpisodeKind>);

fn kinds(s: &str) -> Result<KindList, String> {
    kinds_vec(s).map(KindList)
}

fn kinds_vec(s: &str) -> Result<Vec<EpisodeKind>, String> {
    if s == "all" {
        return Ok(EpisodeKind::ALL.to_vec());
    }
    s.split(',')
        .map(|k| {
            EpisodeKind::parse(k.trim()).ok_or_else(|| {
                format!("unknown kind {k:?}; one of: {}", EpisodeKind::ALL.iter().map(|k| k.name()).collect::<Vec<_>>().join(","))
            })
        })
        .collect()
}

#[derive(Subcommand)]
enum Cmd {
    /// Launch a testnet and run seeded fault episodes against it.
    Run {
        #[arg(long, default_value_t = 7)]
        validators: usize,
        /// Total run time (e.g. 12h, 3m, 90s).
        #[arg(long, value_parser = dur, default_value = "3m")]
        duration: u64,
        #[arg(long, default_value_t = 2)]
        max_faulty: usize,
        #[arg(long, default_value_t = 1)]
        seed: u64,
        /// Path to the hlnode binary.
        #[arg(long)]
        hlnode: PathBuf,
        /// Directory for run-<seed>-<time>/ (testnet, logs, report).
        #[arg(long)]
        workdir: PathBuf,
        /// Background load in tx/s (0 = none).
        #[arg(long, default_value_t = 5.0)]
        load_rate: f64,
        /// External load generator (`sim`); built-in generator otherwise.
        #[arg(long)]
        sim: Option<PathBuf>,
        /// Arguments for --sim ({rate}, {target} = comma-separated URLs, {targets_args}).
        #[arg(long, default_value = "load --rps {rate} --target {target}")]
        sim_args: String,
        /// Report path (default: <run dir>/report.json). Partial reports are
        /// flushed here periodically.
        #[arg(long)]
        report: Option<PathBuf>,
        #[arg(long, value_parser = dur, default_value = "20s")]
        episode_min: u64,
        #[arg(long, value_parser = dur, default_value = "120s")]
        episode_max: u64,
        /// Observation window after each heal.
        #[arg(long, value_parser = dur, default_value = "20s")]
        observe: u64,
        #[arg(long, default_value_t = 10_000)]
        resume_limit_ms: u64,
        /// A non-halting phase without any commit for this long is a stall.
        #[arg(long, value_parser = dur, default_value = "30s")]
        stall_window: u64,
        #[arg(long, value_parser = dur, default_value = "90s")]
        startup_timeout: u64,
        /// Comma-separated episode kinds, or "all".
        #[arg(long, value_parser = kinds, default_value = "all")]
        kinds: KindList,
        /// Extra argument for every `hlnode run` (repeatable), e.g. --node-arg=--min-block-ms --node-arg=200.
        #[arg(long = "node-arg", allow_hyphen_values = true)]
        node_args: Vec<String>,
        /// Funded accounts generated by testnet-gen (for the load).
        #[arg(long, default_value_t = 8)]
        accounts: usize,
        /// Treat height gaps (e.g. snapshot sync) as warnings, not violations.
        #[arg(long)]
        allow_gaps: bool,
        /// Keep node data/logs after the run (default: deleted; report and,
        /// on failure, bounded log tails are kept).
        #[arg(long)]
        keep_workdir: bool,
        /// Skip the post-run commit-proof (QC) verification of the FileStores.
        #[arg(long)]
        no_verify_qcs: bool,
        #[arg(long, value_parser = dur, default_value = "30s")]
        progress_every: u64,
    },
    /// Print the episode schedule a seed produces (no processes started).
    Plan {
        #[arg(long, default_value_t = 7)]
        validators: usize,
        #[arg(long, default_value_t = 2)]
        max_faulty: usize,
        #[arg(long, default_value_t = 1)]
        seed: u64,
        #[arg(long, default_value_t = 10)]
        episodes: usize,
        #[arg(long, value_parser = dur, default_value = "20s")]
        episode_min: u64,
        #[arg(long, value_parser = dur, default_value = "120s")]
        episode_max: u64,
        #[arg(long, value_parser = kinds, default_value = "all")]
        kinds: KindList,
    },
    /// Offline safety check of existing node homes (commits/roots/node.log).
    Check {
        /// Node home directories (e.g. run-*/net/node*).
        homes: Vec<PathBuf>,
        #[arg(long)]
        allow_gaps: bool,
    },
}

fn main() {
    let cli = Cli::parse();
    match cli.cmd {
        Cmd::Run {
            validators,
            duration,
            max_faulty,
            seed,
            hlnode,
            workdir,
            load_rate,
            sim,
            sim_args,
            report,
            episode_min,
            episode_max,
            observe,
            resume_limit_ms,
            stall_window,
            startup_timeout,
            kinds,
            mut node_args,
            accounts,
            allow_gaps,
            keep_workdir,
            no_verify_qcs,
            progress_every,
        } => {
            if episode_min == 0 || episode_min > episode_max {
                eprintln!("--episode-min must be > 0 and <= --episode-max");
                std::process::exit(2);
            }
            // keep node logs small over long runs unless the caller chose a level
            if !node_args.iter().any(|a| a.starts_with("--log-level")) {
                node_args.extend(["--log-level".to_string(), "warn".to_string()]);
            }
            runner::install_signal_handlers();
            let cfg = RunConfig {
                validators,
                duration_ms: duration,
                max_faulty,
                seed,
                hlnode,
                workdir,
                load_rate,
                sim,
                sim_args,
                report,
                episode_min_ms: episode_min,
                episode_max_ms: episode_max,
                observe_ms: observe,
                resume_limit_ms,
                stall_window_ms: stall_window,
                startup_timeout_ms: startup_timeout,
                kinds: kinds.0,
                node_args,
                accounts,
                allow_gaps,
                keep_workdir,
                verify_qcs: !no_verify_qcs,
                progress_every_ms: progress_every,
                flush_every_ms: progress_every.min(30_000),
                ..RunConfig::default()
            };
            match runner::run(cfg) {
                Ok(r) => {
                    println!("{}", serde_json::to_string(&serde_json::json!({
                        "duration_s": r.duration_s, "validators": r.validators, "episodes": r.episodes,
                        "heals": r.heals, "max_resume_ms": r.max_resume_ms, "p50_resume_ms": r.p50_resume_ms,
                        "p99_resume_ms": r.p99_resume_ms, "safety_violations": r.safety_violations,
                        "kills": r.kills, "partitions": r.partitions, "pass": r.pass, "seed": r.seed,
                        "summary": r.summary,
                    })).unwrap());
                    std::process::exit(if r.pass { 0 } else { 1 });
                }
                Err(e) => {
                    eprintln!("hlchaos: {e:#}");
                    std::process::exit(2);
                }
            }
        }
        Cmd::Plan { validators, max_faulty, seed, episodes, episode_min, episode_max, kinds } => {
            let mut s = Scheduler::new(SchedulerConfig { n: validators, max_faulty, min_ms: episode_min, max_ms: episode_max, kinds: kinds.0 }, seed);
            for _ in 0..episodes {
                println!("{}", serde_json::to_string(&s.next_episode(None)).unwrap());
            }
        }
        Cmd::Check { homes, allow_gaps } => {
            let mut c = SafetyChecker::with_homes(&homes, &["console.log"], allow_gaps);
            c.poll();
            println!(
                "{}",
                serde_json::to_string_pretty(&serde_json::json!({
                    "nodes": homes.len(), "safety_violations": c.violation_count, "by_kind": c.by_kind,
                    "violations": c.violations, "stats": c.stats,
                }))
                .unwrap()
            );
            std::process::exit(if c.violation_count == 0 { 0 } else { 1 });
        }
    }
}
